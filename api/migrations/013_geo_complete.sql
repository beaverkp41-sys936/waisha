-- ============
-- EAC INFRASTRUCTURE REFERENCE (operator-collected; ledger 14)
-- ============
create table if not exists geo_ports (
  id serial primary key,
  country text not null,
  name_en text not null,
  kind text not null check (kind in ('sea','lake','dry')),
  category text not null check (category in ('major','minor','icd')),
  unique (country, name_en)
);
create table if not exists geo_border_posts (
  id serial primary key,
  country_a text not null,
  country_b text not null,
  name text not null,
  kind text not null check (kind in ('osbp_land','lake')),
  unique (country_a, country_b, name)
);
create table if not exists geo_airports (
  id serial primary key,
  country text not null,
  name_en text not null,
  city text,
  category text not null check (category in ('international','domestic')),
  unique (country, name_en)
);
grant select on geo_ports, geo_border_posts, geo_airports to app_runtime;
alter table geo_ports enable row level security;
alter table geo_border_posts enable row level security;
alter table geo_airports enable row level security;
create policy ports_read on geo_ports for select to app_runtime using (true);
create policy borders_read on geo_border_posts for select to app_runtime using (true);
create policy airports_read on geo_airports for select to app_runtime using (true);

